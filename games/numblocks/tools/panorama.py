#!/usr/bin/env python3
"""The title screen's panoramas: a Minecraft version's six cubemap faces, packed
for the game into src/panorama.c (RGB565, 160 x 160 a face - the picture the game
draws is 160 x 120, so a face is a texel a picture pixel at its centre).

The pictures are the clients' own title panoramas, from the Minecraft Wiki
(1024 x 1024 a face there):

  1.16  https://minecraft.wiki/w/Category:Outdated_panorama_textures   1.16_panorama_0..5.png
  1.20  https://minecraft.wiki/w/Category:Panorama_textures            1.20_panorama_0..5.png
  1.21  https://minecraft.wiki/w/Category:Panorama_textures            1.21_panorama_0..5.png

--fetch downloads them into the texture dump, downscaled to 256 x 256 (1.6 x the
pack's 160, room for a bigger one later): the dump's copy is what the pack reads,
so a pack needs no network other than --fetch's. Each face is packed to RGB565,
the colour the screen itself holds, and the faces run 0..5 as the client shoots
them - 0..3 the horizon clockwise (south, west, north, east), 4 up, 5 down - and
render.c samples them by the ray's direction (the mapping is the client's:
/camera rot 0 0, 0 90, 0 180, 0 270, -90 0, 90 0).

    python3 tools/panorama.py [--fetch] [--root DIR] [--preview DIR]

--root is the texture dump (default: ../../minecraft-textures). --preview writes
what each panorama looks like at the title (a 320 x 240 picture a version, from
the packed texels - the game's own camera), for the eye's check.
"""
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DUMP = os.path.join(ROOT, '..', '..', 'minecraft-textures')
SUBDIR = os.path.join('textures', 'gui', 'title', 'background')

# the version's name (the option's label), its dump folder, and its wiki file stem
VERSIONS = [('1.16', '1.16'), ('1.20', '1.20'), ('1.21', '1.21')]
FACE = 160     # texels a face in the pack: the picture is 160 x 120 and 86 degrees of the
               # face's 90 fill its width, so this is a texel a picture pixel, the most the
               # screen can show; bigger only oversamples (and the app space is finite)
STORE = 256    # the dump copy's size (1.6 x the pack, room for a bigger one)

WIKI = 'https://minecraft.wiki/images/%s_panorama_%d.png'


def stored(root, ver, f):
    return os.path.join(root, SUBDIR, ver, 'panorama_%d.png' % f)


def fetch(root, ver):
    """the six faces from the wiki into the dump, at STORE x STORE"""
    from PIL import Image
    import io
    for f in range(6):
        url = WIKI % (ver, f)
        print('fetch', url)
        req = urllib.request.Request(url, headers={'User-Agent': 'NumPlay-NumBlocks/1.0 (title panorama packer)'})
        with urllib.request.urlopen(req) as r:
            im = Image.open(io.BytesIO(r.read())).convert('RGB')
        if im.size != (1024, 1024):
            sys.exit('unexpected size %s for %s' % (im.size, url))
        im = im.resize((STORE, STORE), Image.LANCZOS)
        p = stored(root, ver, f)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        im.save(p, optimize=True)


def pack_face(im):
    """a face as FACE x FACE RGB565 texels (the game's own colour, no palette)

    No dithering or quantizing: 565 is what the screen holds, so the picture is the
    source's own colours, and at a face nearly a texel a picture pixel the sky's
    gradients stay smooth."""
    from PIL import Image
    im = im.convert('RGB').resize((FACE, FACE), Image.LANCZOS)
    px = list(im.get_flattened_data() if hasattr(im, 'get_flattened_data') else im.getdata())
    return [rgb565(r, g, b) for r, g, b in px]


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def write_c(root, out):
    from PIL import Image
    tex = []
    for ver, folder in VERSIONS:
        t = []
        for f in range(6):
            path = stored(root, folder, f)
            if not os.path.exists(path):
                sys.exit('missing %s - run with --fetch first' % path)
            t.append(pack_face(Image.open(path)))
        tex.append(t)
    out = ['/* Generated by tools/panorama.py from the Minecraft Wiki: the title screen\'s',
           ' * panoramas (see the tool). Six %d x %d faces a version, RGB565, a texel a' % (FACE, FACE),
           ' * byte pair; the faces run 0..5 as the client shoots them: 0..3 the horizon',
           ' * clockwise (south, west, north, east), 4 up, 5 down. */',
           '#include "panorama.h"', '']
    out.append('const uint16_t pan_px[PAN_N][6][PAN_FACE * PAN_FACE] = {')
    for k, (ver, folder) in enumerate(VERSIONS):
        out.append('  {   /* %s */' % ver)
        for row in tex[k]:
            out.append('    {' + ','.join('0x%04X' % v for v in row) + '},')
        out.append('  },')
    out.append('};')
    open(os.path.join(ROOT, 'src', 'panorama.c'), 'w').write('\n'.join(out) + '\n')
    print('src/panorama.c: %d faces, %d bytes of texels' % (sum(len(t) for t in tex), 2 * FACE * FACE * 18))


def preview(root, out):
    """what the packed panorama looks like at the title (320 x 240, the game's camera)"""
    from PIL import Image
    import math
    os.makedirs(out, exist_ok=True)
    packed = [[pack_face(Image.open(stored(root, folder, f))) for f in range(6)] for ver, folder in VERSIONS]

    def texel(face, u, v):
        u = 0 if u < 0 else FACE - 1 if u > FACE - 1 else int(u)
        v = 0 if v < 0 else FACE - 1 if v > FACE - 1 else int(v)
        c = face[v * FACE + u]
        return ((c >> 11) & 0x1F) << 3, ((c >> 5) & 0x3F) << 2, (c & 0x1F) << 3

    def sample(faces, dx, dy, dz):
        ax, ay, az = abs(dx), abs(dy), abs(dz)
        if ax >= ay and ax >= az:
            f, s = (3, dx) if dx > 0 else (1, -dx)
            u = 0.5 + 0.5 * dz / s if dx > 0 else 0.5 - 0.5 * dz / s
            v = 0.5 - 0.5 * dy / s
        elif ay >= az:
            f, s = (4, dy) if dy > 0 else (5, -dy)
            u = 0.5 - 0.5 * dx / s if dy > 0 else 0.5 + 0.5 * dx / s
            v = 0.5 + 0.5 * dz / s if dy > 0 else 0.5 - 0.5 * dz / s
        else:
            f, s = (0, dz) if dz > 0 else (2, -dz)
            u = 0.5 - 0.5 * dx / s if dz > 0 else 0.5 + 0.5 * dx / s
            v = 0.5 - 0.5 * dy / s
        return texel(faces[f], u * FACE, v * FACE)

    W, H, tanv = 160, 120, 0.70020754
    tanh = tanv * W / H
    yaws = [0, 60, 120, 240]   # a few turns, as the title does
    for k, faces in enumerate(packed):
        sheet = Image.new('RGB', (W * len(yaws) * 2, H * 2))
        for yaw in yaws:
            yr = math.radians(yaw)
            pr = math.radians(8)   # the title camera looks down a little
            cy, sy, cp, sp = math.cos(yr), math.sin(yr), math.cos(pr), math.sin(pr)
            fwx, fwy, fwz = -sy * cp, -sp, cy * cp
            rgx, rgz = -cy, -sy
            upx, upy, upz = 0 * fwz - rgz * fwy, rgz * fwx - rgx * fwz, rgx * fwy - 0 * fwx
            im = Image.new('RGB', (W, H))
            px = im.load()
            for y in range(H):
                sv = (1 - 2 * (y + 0.5) / H) * tanv
                for x in range(W):
                    su = (2 * (x + 0.5) / W - 1) * tanh
                    px[x, y] = sample(faces, fwx + upx * sv + rgx * su, fwy + upy * sv, fwz + upz * sv + rgz * su)
            sheet.paste(im.resize((W * 2, H * 2), Image.NEAREST), (W * 2 * yaws.index(yaw), 0))
        sheet.save(os.path.join(out, '%s.png' % VERSIONS[k][0]))
    print('previews:', ', '.join(os.path.join(out, '%s.png' % v) for v, f in VERSIONS))


def main():
    args = sys.argv[1:]
    root, prefetch, preview_dir = DUMP, False, None
    i = 0
    while i < len(args):
        a = args[i]
        if a == '--fetch':
            prefetch = True
        elif a == '--root':
            i += 1
            root = args[i]
        elif a == '--preview':
            i += 1
            preview_dir = args[i]
        else:
            sys.exit('unknown argument %r' % a)
        i += 1
    if prefetch:
        for ver, folder in VERSIONS:
            fetch(root, folder)
    if preview_dir:
        preview(root, preview_dir)
    else:
        write_c(root, None)


if __name__ == '__main__':
    main()
